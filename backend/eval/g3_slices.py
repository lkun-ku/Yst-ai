"""G3' 分片账本 —— **唯一**记录"哪一片覆盖了哪一段序号"的地方。

## 为什么必须是唯一一份（2026-03-04 踩到）

两个脚本都要回答同一个问题"这一片覆盖了哪一段"：

- `fill_g3_gaps.py`（算缺口）：答错 → **缺的题被当成已覆盖**，缺口被少算；
- `sum_g3_slices.py`（合并结论）：答错 → **覆盖被重复计数**，实测报出 `n=287 > 数据集 254 道`。

我第一版让两边各写一份，于是立刻分叉：`fill` 知道 `p1b/p3b` 没测完（不计覆盖），
`sum` 不知道（当成完整的算进去）。**同一件事实在两处各有一份，就一定会有一处是错的。**

## 为什么老分片只能手记

`p1b` / `p2` / `p3b` / `p4` / `p5` / `s1` 都跑在"报告头写区间"之前，产物里**没有任何位置信息**，
只能按它们当时的 `--offset/--limit` 记在这里。新分片会自动在报告头写 `第 a–b 道`，
不再需要登记 —— **这张表只增不减地承载历史，新数据不应再往这里加。**
"""

from __future__ import annotations

#: tag → 该片**声明的**覆盖序号区间（含首含尾）。
#:
#: ⚠️ 这是"它声称覆盖的范围"，**不是"它真的测到了"** —— 两者之差就是 `POLLUTED_TAGS`。
LEGACY_SPANS: dict[str, tuple[int, int]] = {
    "s1": (0, 29),
    "p1b": (0, 50),
    "p2": (51, 101),
    "p3b": (102, 152),
    "p4": (153, 203),
    "p5": (204, 253),
}

#: 已知**没测完**的片：撞上 LLM 额度耗尽（主通道 402 / 备用通道欠费），
#: 实测 `p1b` 只出 18/51、`p3b` 只出 15/51。
#:
#: 它们**不得**被当作覆盖（否则缺口被少算），也**不得**进主数字（否则覆盖被重复计数
#: —— 它们的区间与 `s1` / `g30` / `g102` 有重叠）。两条规则方向不同，理由同一条：
#: **没测完的片，对"覆盖了多少"和"误杀率是多少"这两个问题都给不出答案。**
POLLUTED_TAGS = frozenset({"p1b", "p3b"})


def span_of(tag: str, header_span: tuple[int, int] | None = None) -> tuple[int, int] | None:
    """取某一片的覆盖区间：报告头写了就采信它自己的声明，否则查历史账本。"""
    return header_span if header_span else LEGACY_SPANS.get(tag)
