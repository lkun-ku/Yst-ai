"""G3 评测里**不依赖模型**的那部分：N1 负样本的构造与回放判定。

## 为什么这类断言值得单独写

N1 负样本的结论（"闸门拦得住"）完全由 `_neg_blocked` 这一个纯函数决定 ——
它不需要模型、不需要额度、结果确定。**这种逻辑最该被测死**：
一旦它算错，"闸门有效"这个结论就是假的，而假结论比没有结论更糟。

## 回放为什么在原理上成立

G3 的判定只看两者：**盲答结果**与**题目自带答案**。与"模型是怎么答出这个结果的"无关。
所以同一次盲答能同时回答两件事 —— 对原答案键是"误杀"吗，对改错的答案键"拦得住"吗。
这条性质让负样本评测变成**零额外调用**，不必再造一批题、再花一遍额度。
"""

from eval.g3_eval import _corrupt_key, _neg_blocked

#: 正确答案是 B；A/C/D 都是错误选项
_Q = {
    "type": "single",
    "stem": "下列哪一项符合素质教育的要求？",
    "options": [
        {"key": "A", "text": "只抓升学率"},
        {"key": "B", "text": "面向全体学生"},
        {"key": "C", "text": "只培养尖子生"},
        {"key": "D", "text": "取消全部课外活动"},
    ],
    "answer": ["B"],
}


def test_把答案键改成一个错误选项():
    assert _corrupt_key(_Q) == ["A"], "取第一个不在答案里的选项，结果必须确定"


def test_没有任何错误选项时不构造负样本():
    """全选对（多选题的边界形态）时无法构造 N1 → 返回空，该题不计入负样本。
    不能硬造一个：那样真值就不确定了。"""
    assert _corrupt_key({**_Q, "answer": ["A", "B", "C", "D"]}) == []


def test_回放_模型答对时改错的键会被拦():
    assert _neg_blocked(_Q, (("B",), ("B",), ("B",))) is True


def test_回放_盲答不一致时也算拦下():
    """`agree=False` 本就是 G3 的拦截条件之一（答案有歧义）。"""
    assert _neg_blocked(_Q, (("B",), ("C",), ("B",))) is True


def test_回放_模型恰好答成改错后的键时不算拦下():
    """严谨的边界：模型盲答稳定地给出 A，而键恰好被改成 A → `matches` 为真 →
    回放说"没拦"。这不是闸门的错，但**也不能**把这题算成"拦住了" ——
    把这条钉住，免得以后有人把负样本拦截率当成"无论如何都会很高"。
    """
    assert _neg_blocked(_Q, (("A",), ("A",), ("A",))) is False
